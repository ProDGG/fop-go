#!/usr/bin/env python3
"""Generate internal/fo/props_gen.go from Apache FOP's foproperties.xml.

Usage: tools/genprops.py /path/to/xmlgraphics-fop > internal/fo/props_gen.go
Only the 'inherited' flag and plain, context independent default values are taken.
"""
import re, subprocess, sys

root = sys.argv[1]
src = open(root + '/fop-core/src/main/codegen/fo/foproperties.xml', encoding='utf-8').read()
try:
    rev = subprocess.run(['git', '-C', root, 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip()
except Exception:
    rev = 'unknown'
inherited, defaults = [], {}
for p in re.findall(r'<property>(.*?)</property>', src, re.S):
    n = re.search(r'<name>([^<]+)</name>', p)
    if not n:
        continue
    name = n.group(1)
    i = re.search(r'<inherited[^>]*>(true|false)</inherited>', p)
    if i and i.group(1) == 'true':
        inherited.append(name)
    d = re.search(r'<default(?: ([^>]*))?>([^<]*)</default>', p)
    if d and d.group(2).strip() and not (d.group(1) and ('subproperty' in d.group(1) or 'contextdep' in d.group(1))):
        defaults[name] = d.group(2).strip()
print('// Code generated by tools/genprops.py from Apache FOP foproperties.xml (rev %s); DO NOT EDIT.' % rev)
print('package fo\n')
print('var fopInherited = map[string]bool{')
for n in sorted(set(inherited)):
    print('\t"%s": true,' % n)
print('}\n')
print('var fopInitial = map[string]string{')
for n in sorted(defaults):
    print('\t"%s": "%s",' % (n, defaults[n].replace('"', '\\"')))
print('}')
