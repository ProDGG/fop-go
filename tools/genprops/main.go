// Command genprops generates internal/fo/props_gen.go from Apache FOP's
// foproperties.xml.
//
//	FOP_SRC=/path/to/xmlgraphics-fop go generate ./internal/fo
//	go run ./tools/genprops -o internal/fo/props_gen.go /path/to/xmlgraphics-fop
//
// Only the "inherited" flag and plain, context independent default values are taken.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	propRe    = regexp.MustCompile(`(?s)<property>(.*?)</property>`)
	nameRe    = regexp.MustCompile(`<name>([^<]+)</name>`)
	inheritRe = regexp.MustCompile(`<inherited[^>]*>(true|false)</inherited>`)
	defaultRe = regexp.MustCompile(`<default(?: ([^>]*))?>([^<]*)</default>`)
)

// generate renders the Go source for the given foproperties.xml text.
func generate(src, rev string) string {
	inherited := map[string]bool{}
	defaults := map[string]string{}
	for _, m := range propRe.FindAllStringSubmatch(src, -1) {
		p := m[1]
		n := nameRe.FindStringSubmatch(p)
		if n == nil {
			continue
		}
		name := n[1]
		if i := inheritRe.FindStringSubmatch(p); i != nil && i[1] == "true" {
			inherited[name] = true
		}
		if d := defaultRe.FindStringSubmatch(p); d != nil && strings.TrimSpace(d[2]) != "" &&
			!(d[1] != "" && (strings.Contains(d[1], "subproperty") || strings.Contains(d[1], "contextdep"))) {
			defaults[name] = strings.TrimSpace(d[2])
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/genprops from Apache FOP foproperties.xml (rev %s); DO NOT EDIT.\n", rev)
	b.WriteString("package fo\n\nvar fopInherited = map[string]bool{\n")
	for _, n := range sortedKeys(inherited) {
		fmt.Fprintf(&b, "\t%q: true,\n", n)
	}
	b.WriteString("}\n\nvar fopInitial = map[string]string{\n")
	names := make([]string, 0, len(defaults))
	for n := range defaults {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, defaults[n])
	}
	b.WriteString("}\n")
	return b.String()
}

func sortedKeys(m map[string]bool) []string {
	var k []string
	for n := range m {
		k = append(k, n)
	}
	sort.Strings(k)
	return k
}

func main() {
	out := flag.String("o", "", "output file (default stdout)")
	flag.Usage = func() {
		fmt.Fprintln(os.Stderr, "usage: genprops [-o props_gen.go] /path/to/xmlgraphics-fop")
		flag.PrintDefaults()
	}
	flag.Parse()
	if flag.NArg() != 1 {
		flag.Usage()
		os.Exit(2)
	}
	root := flag.Arg(0)
	src, err := os.ReadFile(filepath.Join(root, "fop-core/src/main/codegen/fo/foproperties.xml"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "genprops:", err)
		os.Exit(1)
	}
	rev := "unknown"
	if o, err := exec.Command("git", "-C", root, "rev-parse", "--short", "HEAD").Output(); err == nil {
		rev = strings.TrimSpace(string(o))
	}
	text := generate(string(src), rev)
	var w io.Writer = os.Stdout
	if *out != "" {
		f, err := os.Create(*out)
		if err != nil {
			fmt.Fprintln(os.Stderr, "genprops:", err)
			os.Exit(1)
		}
		defer f.Close()
		w = f
	}
	if _, err := io.Copy(w, bytes.NewReader([]byte(text))); err != nil {
		fmt.Fprintln(os.Stderr, "genprops:", err)
		os.Exit(1)
	}
}
